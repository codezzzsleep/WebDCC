import { chromium, type Browser } from '@playwright/test';
import { expect, it } from 'vitest';
import type { AdapterEvent, CreateOpts, EventData, TraceFrame } from '@webdcc/protocol';
import { FakeAdapter } from '../packages/testing/fake-adapter/src/index.js';
import { CodexAdapter } from '../packages/adapters/codex/src/adapter.js';
import { createSourceTestApp } from './helpers.js';

it('native plan text streams once, survives refresh and reconnect, uses the real final and preserves an interrupted draft', async () => {
  const ctx = await createSourceTestApp(); let browser: Browser | undefined;
  try {
    let receive!: (id: string, event: AdapterEvent) => void; let opts!: CreateOpts;
    const adapter = new FakeAdapter({ id: 'codex' }); adapter.onEvent = callback => { receive = callback; };
    const create = adapter.create.bind(adapter); adapter.create = async value => { opts = value; return create(value); };
    adapter.send = async () => undefined;
    ctx.manager.registerAdapter(adapter);
    const workspace = ctx.store.createWorkspace('Native plans', ctx.dataDir);
    const session = await ctx.manager.createSession({ workspaceId: workspace.id, agent: 'codex' });
    await ctx.manager.send(session.id, { text: 'Plan the work.' }, 'native-plan-input');
    const replay = CodexAdapter.replay(session.id, session.nativeId); let index = 0;
    const feed = (method: string, params: Record<string, unknown>): void => {
      const frame: TraceFrame = { i: ++index, t: index, dir: 'in', ch: 'rpc',
        frame: { method, params: { threadId: session.nativeId, ...params } } };
      const receipt = opts.nativeEvents!.record(frame);
      for (const event of replay.feed(frame)) receive(session.id, { ...event, runtime: opts.runtime, nativeEnvelopeId: receipt.envelopeId });
    };
    feed('turn/started', { turn: { id: 'a' } });
    feed('turn/plan/updated', { turnId: 'a', explanation: null, plan: [{ step: 'Native checklist remains separate', status: 'in_progress' }] });
    feed('item/started', { turnId: 'a', item: { type: 'plan', id: 'same', text: '' } });
    const draft = '  # 临时计划\n\n- **Draft** 😀\n';
    feed('item/plan/delta', { turnId: 'a', itemId: 'same', delta: draft });
    await ctx.app.listen({ host: '127.0.0.1', port: 0 });
    const address = ctx.app.server.address(); if (!address || typeof address === 'string') throw new Error('Missing listener');
    const base = 'http://127.0.0.1:' + address.port;
    browser = await chromium.launch({ headless: true }); const page = await browser.newPage();
    const errors: string[] = []; const frames: Record<string, unknown>[] = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('websocket', socket => socket.on('framereceived', frame => frames.push(JSON.parse(String(frame.payload)) as Record<string, unknown>)));
    await page.context().addCookies([{ name: 'wdcc-auth', value: ctx.cookie.slice('wdcc-auth='.length), url: base }]);
    await page.goto(base + '/s/' + session.id);
    const text = page.getByTestId('native-plan-text');
    await expect.poll(() => text.getAttribute('data-raw-text')).toBe(draft);
    expect(await text.count()).toBe(1);
    await page.reload();
    await expect.poll(() => text.getAttribute('data-raw-text')).toBe(draft);
    feed('item/plan/delta', { turnId: 'a', itemId: 'same', delta: 'More live text\n' });
    await expect.poll(() => text.getAttribute('data-raw-text')).toBe(draft + 'More live text\n');
    await page.getByTestId('plan-panel').locator('button').click();
    expect(await page.getByTestId('plan-panel').textContent()).toContain('Native checklist remains separate');
    const final = '\t# Final 原生计划\n\n- [ ] **Authoritative** 😀\n\n<script>window.planInjected = true</script>\n';
    feed('item/completed', { turnId: 'a', item: { type: 'plan', id: 'same', text: final } });
    await expect.poll(() => text.getAttribute('data-raw-text')).toBe(final);
    expect(await text.count()).toBe(1);
    expect(await page.getByTestId('plan-panel').textContent()).toContain('Native checklist remains separate');
    feed('item/plan/delta', { turnId: 'a', itemId: 'same', delta: ' POISON' });
    feed('item/started', { turnId: 'a', item: { type: 'plan', id: 'same', text: '' } });
    feed('item/completed', { turnId: 'a', item: { type: 'plan', id: 'same', text: final } });
    expect(await text.getAttribute('data-raw-text')).toBe(final);
    expect(await page.evaluate(() => 'planInjected' in window)).toBe(false);
    feed('turn/completed', { turn: { id: 'a', status: 'completed' } });
    await expect.poll(() => page.locator('.turn-running').count()).toBe(0);
    await page.reload();
    await page.locator('.turn-summary').first().click();
    await expect.poll(() => text.getAttribute('data-raw-text')).toBe(final);
    const a = ctx.store.allEvents(session.id).filter(event => event.kind === 'plan' && (event.data as EventData['plan']).text !== undefined);
    expect(a).toHaveLength(1); expect(a[0]!.itemKey).toBe('same'); expect(a[0]!.nativeEnvelopeId).toBeDefined();
    feed('turn/started', { turn: { id: 'b' } });
    feed('item/plan/delta', { turnId: 'b', itemId: 'same', delta: 'B interrupted draft\n' });
    await expect.poll(() => page.locator('.turn-running').getByTestId('native-plan-text').getAttribute('data-raw-text')).toBe('B interrupted draft\n');
    feed('turn/completed', { turn: { id: 'b', status: 'interrupted' } });
    await expect.poll(() => page.locator('.turn-running').count()).toBe(0);
    await page.locator('.turn-summary').last().click();
    const last = page.locator('.turn').last();
    await expect.poll(() => last.getByTestId('native-plan-text').getAttribute('data-raw-text')).toBe('B interrupted draft\n');
    expect(await last.getByTestId('native-plan').textContent()).toContain('计划未完成');
    await page.reload(); await page.locator('.turn-summary').last().click();
    await expect.poll(() => last.getByTestId('native-plan-text').getAttribute('data-raw-text')).toBe('B interrupted draft\n');
    const stored = ctx.store.allEvents(session.id).filter(event => event.kind === 'plan' && (event.data as EventData['plan']).text !== undefined);
    expect(stored).toHaveLength(2);
    expect(new Set(stored.map(event => event.turnId)).size).toBe(2);
    expect(stored[1]!.data).toMatchObject({ incomplete: true });
    expect(frames.some(frame => frame['op'] === 'delta' && frame['itemKey'] === 'same' && typeof frame['turnId'] === 'string')).toBe(true);
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await ctx.close(); }
}, 30_000);
