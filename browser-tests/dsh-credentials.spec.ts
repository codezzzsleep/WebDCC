import { chromium, expect as browserExpect, type Browser } from '@playwright/test';
import { expect, it } from 'vitest';
import { createSourceTestApp } from './helpers.js';
import { settingsHost } from '../packages/server/test/fixtures/dsh-settings.js';

it('Chromium previews references, cancels keys, saves to the exact account and creates an isolated Provider', async () => {
  const host = await settingsHost(), ctx = await createSourceTestApp(); let browser: Browser | undefined;
  try {
    const providers = host.state.namespaces[0]!.value['providers'] as Record<string, Record<string, unknown>>;
    providers['other']!['apiKeyEnv'] = 'OTHER_KEY'; providers['other']!['models'] = [{ id: 'other-model' }];
    const other = structuredClone(providers['other']);
    const defaults = structuredClone(host.state.namespaces[1]!.value);
    await ctx.dsh.save({ url: host.url, cookie: 'fixture-cookie', connectedAt: '2026-11-15T00:00:00Z' });
    const base = await ctx.app.listen({ host: '127.0.0.1', port: 0 });
    browser = await chromium.launch({ headless: true }); const page = await browser.newPage();
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.context().addCookies([{ name: 'wdcc-auth', value: ctx.cookie.slice('wdcc-auth='.length), url: base }]);
    await page.goto(`${base}/settings/providers`);
    await page.getByRole('tab').filter({ hasText: 'DeepSeek' }).click();
    const ref = page.getByLabel('凭据引用 apiKeyEnv');
    await browserExpect(ref).toHaveValue('FIXTURE_KEY');
    await ref.fill('TARGET_NEW_KEY'); await page.getByRole('button', { name: '查看引用变更', exact: true }).click();
    await browserExpect(page.getByTestId('dsh-reference-preview')).toContainText(host.url);
    expect(providers['target']!['apiKeyEnv']).toBe('FIXTURE_KEY');
    await page.getByRole('button', { name: '取消引用变更' }).click();
    expect(host.calls.filter(call => call.method === 'settings/mutate')).toHaveLength(0);
    await ref.fill('TARGET_NEW_KEY'); await page.getByRole('button', { name: '查看引用变更', exact: true }).click();
    await page.getByRole('button', { name: '确认引用变更' }).click();
    await browserExpect(ref).toHaveValue('TARGET_NEW_KEY');
    const password = page.getByLabel('新的 API 密钥'); const secret = 'browser-only-fixture-key';
    await password.fill(secret); await page.getByRole('button', { name: '检查密钥保存目标' }).click();
    await browserExpect(page.getByTestId('dsh-key-preview')).toContainText('TARGET_NEW_KEY');
    expect(await page.getByTestId('dsh-key-preview').textContent()).not.toContain(secret);
    expect(host.credentials.has('TARGET_NEW_KEY')).toBe(false);
    await page.getByRole('button', { name: '取消密钥保存' }).click();
    await browserExpect(password).toHaveValue(''); expect(host.credentials.has('TARGET_NEW_KEY')).toBe(false);
    await password.fill(secret); await page.getByRole('button', { name: '检查密钥保存目标' }).click();
    await page.getByRole('button', { name: '确认保存密钥' }).click();
    await expect.poll(() => host.credentials.get('TARGET_NEW_KEY')).toBe(secret);
    await browserExpect(password).toHaveValue('');
    expect(host.credentials.get('FIXTURE_KEY')).toBe('original fixture key');
    expect(host.credentials.get('OTHER_KEY')).toBe('other fixture key');
    await page.getByLabel('DSH Provider', { exact: true }).selectOption('other');
    await browserExpect(ref).toHaveValue('OTHER_KEY'); await browserExpect(password).toHaveValue('');

    await page.getByText('新增 DSH Provider', { exact: true }).click();
    const create = page.getByTestId('dsh-create-provider');
    await create.getByLabel('Provider ID', { exact: true }).fill('third');
    await create.getByLabel('Base URL', { exact: true }).fill('https://third.example/v1');
    await create.getByLabel('初始模型 ID', { exact: true }).fill('third-model');
    await create.getByLabel('独立凭据引用', { exact: true }).fill('THIRD_KEY');
    await create.getByRole('button', { name: '查看新增配置' }).click();
    await create.getByRole('button', { name: '取消创建' }).click();
    expect((host.state.namespaces[0]!.value['providers'] as Record<string, unknown>)['third']).toBeUndefined();
    await create.getByRole('button', { name: '查看新增配置' }).click();
    await create.getByRole('button', { name: '确认创建 Provider' }).click();
    await browserExpect(ref).toHaveValue('THIRD_KEY');
    const thirdSecret = 'third browser fixture key';
    await password.fill(thirdSecret); await page.getByRole('button', { name: '检查密钥保存目标' }).click();
    await page.getByRole('button', { name: '确认保存密钥' }).click();
    await expect.poll(() => host.credentials.get('THIRD_KEY')).toBe(thirdSecret);
    expect((host.state.namespaces[0]!.value['providers'] as Record<string, unknown>)['other']).toEqual(other);
    expect(host.state.namespaces[1]!.value).toEqual(defaults);
    const database = (ctx.store as unknown as { db: { serialize: () => Buffer } }).db.serialize();
    expect(database.includes(Buffer.from(secret))).toBe(false);
    expect(database.includes(Buffer.from(thirdSecret))).toBe(false);
    await page.reload(); await page.getByRole('tab').filter({ hasText: 'DeepSeek' }).click();
    await page.getByLabel('DSH Provider', { exact: true }).selectOption('third');
    await browserExpect(ref).toHaveValue('THIRD_KEY'); await browserExpect(password).toHaveValue('');
    expect(errors).toEqual([]);
  } finally { await browser?.close(); await ctx.close(); await host.close(); }
}, 60_000);
