import { mkdtemp, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { afterEach, expect, it } from 'vitest';
import { InteractionRecorder } from '../src/interaction-recorder.js';
let root: string;
afterEach(async () => { if (root !== undefined) await rm(root, { recursive: true, force: true }); });
it('correlates raw/model/Web/disk evidence, redacts secrets and reports incomplete requests', async () => {
  root = await mkdtemp(join(tmpdir(), 'wdcc-recorder-'));
  const recorder = new InteractionRecorder(root); await recorder.init();
  recorder.addSecret('private-test-token');
  recorder.bind({ sessionId: 's', agent: 'claude-code', workspaceId: 'w', cwd: root, nativeId: 'native' });
  await recorder.turnContext('s', 'turn');
  recorder.record('s', 'web', 'command', { text: 'private-test-token', authorization: 'test-value' }, 'out');
  recorder.sink('s').record?.({ i: 1, t: 0, dir: 'in', ch: 'sdk', frame: { type: 'assistant' } });
  recorder.record('s', 'model-http', 'request', { requestId: 'probe', value: { path: '/api/hello' } });
  recorder.record('s', 'model-http', 'complete', { requestId: 'probe' });
  recorder.record('s', 'model-http', 'request', { requestId: 'req', value: { path: '/v1/messages?beta=true' } });
  await writeFile(join(root, 'a.txt'), 'before');
  recorder.observeFiles('s', { type: 'item.start', itemKey: 'file', kind: 'file.change', data: { changes: [{ path: 'a.txt', kind: 'modify', added: 1, removed: 1 }], status: 'running' } });
  await writeFile(join(root, 'a.txt'), 'actual disk contents');
  recorder.observeFiles('s', { type: 'item.complete', itemKey: 'file', kind: 'file.change', data: { changes: [{ path: 'a.txt', kind: 'modify', added: 1, removed: 1 }], status: 'completed' } });
  const summary = await recorder.summary('s');
  expect(summary).toMatchObject({ nativeFrames: 1, modelRequests: 1, fileOperations: 2, incomplete: true });
  recorder.record('s', 'model-http', 'complete', { requestId: 'req', outcome: 'failed' });
  expect((await recorder.summary('s')).incomplete).toBe(false);
  const text = await recorder.read('s'); expect(text).not.toContain('private-test-token'); expect(text).not.toContain('test-value');
  const rows = text.trim().split('\n').map(line => JSON.parse(line));
  expect(rows.every(row => row.context.turnId === 'turn')).toBe(true);
  expect(rows.find(row => row.channel === 'after').value.sha256).toBe(createHash('sha256').update(await readFile(join(root, 'a.txt'))).digest('hex'));
  expect((await stat(join(recorder.directory, 's.jsonl'))).mode & 0o777).toBe(0o600);
});
